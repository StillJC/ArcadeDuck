{
  const u64 previous_masks = previous_cipherwords ^ previous_plainwords;
  return static_cast<u16>(((previous_masks >> 9) &
                           (Parity64(UINT64_C(0x0000000010065810) & previous_cipherwords) ^
                            Parity64(UINT64_C(0x0000000021005810) & previous_plainwords)) &
                           1)
                          << 10);
}

