constexpr void InitializeType2StateImpl(const Type2Logic& logic, Type2State& state, u8 iv)
{
  const std::array<u64, 16>& history = logic.initial_history ? *logic.initial_history : DEFAULT_TYPE2_INITIAL_HISTORY;
  state.previous_cipherwords = history[iv & 0x0f];
  state.previous_plainwords = 0;
  state.mask = 0;
}

constexpr u16 DecodeType2WordImpl(const Type2Logic& logic, Type2State& state, u16 cipher_word,
                                  std::span<const u8> nonlinear_table)
{
  const u16 plain_word = static_cast<u16>(cipher_word ^ state.mask);
  state.previous_cipherwords = (state.previous_cipherwords << 16) | cipher_word;
  state.previous_plainwords = (state.previous_plainwords << 16) | plain_word;

  u16 mask = 0;
  for (s32 bit = 15; bit >= 0; bit--)
  {
    mask = static_cast<u16>(mask << 1);
    mask ^= static_cast<u16>(Parity64(logic.cipher_masks[static_cast<size_t>(bit)] & state.previous_cipherwords));
    mask ^= static_cast<u16>(Parity64(logic.plain_masks[static_cast<size_t>(bit)] & state.previous_plainwords));
  }
  mask ^= logic.xor_mask;

  if (logic.nonlinear_table_shift != 0)
  {
    if (!nonlinear_table.empty())
    {
      const u32 bit = (nonlinear_table[state.nonlinear_count / 8] >> (7 - (state.nonlinear_count % 8))) & 1u;
      state.nonlinear_count++;
      if (state.nonlinear_count >= nonlinear_table.size() * 8)
        state.nonlinear_count = 0;
      mask ^= static_cast<u16>(bit << logic.nonlinear_table_shift);
    }
  }
  else if (logic.nonlinear)
  {
    mask ^= logic.nonlinear(state.previous_cipherwords, state.previous_plainwords);
  }

  state.mask = mask;
  return plain_word;
}

constexpr bool ValidateStarTrigonType2KnownAnswer()
{
  // First 32 bytes of Star Trigon's protected program stream (IV 0). The
  // plaintext is the MIPS entry sequence J 0x80012220, NOP, then an address
  // ladder beginning at 0x800126BC.
  constexpr std::array<u16, 16> cipher = {
    0x4888, 0xbed6, 0x1c94, 0x1b5c, 0xa21c, 0x1d38, 0x082b, 0xdf32,
    0x4600, 0x5275, 0x985d, 0x73d4, 0xa392, 0x9563, 0x86e1, 0xebc8,
  };
  constexpr std::array<u16, 16> expected_plain = {
    0x4888, 0x0800, 0x0000, 0x0000, 0x26bc, 0x8001, 0x26cc, 0x8001,
    0x26dc, 0x8001, 0x26ec, 0x8001, 0x26fc, 0x8001, 0x270c, 0x8001,
  };

  Type2State state;
  InitializeType2StateImpl(STARTRGN_TYPE2, state, 0);
  for (size_t i = 0; i < cipher.size(); i++)
  {
    if (DecodeType2WordImpl(STARTRGN_TYPE2, state, cipher[i], {}) != expected_plain[i])
      return false;
  }

  return true;
}

static_assert(ValidateStarTrigonType2KnownAnswer());

