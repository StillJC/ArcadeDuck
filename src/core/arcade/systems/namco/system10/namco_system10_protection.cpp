const MemNProfile* FindMemNProfile(std::string_view hardware_profile)
{
  const auto it =
    std::find_if(s_memn_profiles.begin(), s_memn_profiles.end(),
                 [hardware_profile](const MemNProfile& p) { return p.hardware_profile == hardware_profile; });
  return (it != s_memn_profiles.end()) ? &(*it) : nullptr;
}

u16 DecodeMemNStaticWord(const MemNProfile& profile, u16 raw_word, u16 data_xor)
{
  const u16 value = static_cast<u16>(raw_word ^ data_xor);
  u16 result = 0;
  for (size_t i = 0; i < profile.static_bit_order.size(); i++)
    result = static_cast<u16>((result << 1) | ((value >> profile.static_bit_order[i]) & 1u));
  return result;
}

void InitializeType2State(const Type2Logic& logic, Type2State& state, u8 iv)
{
  InitializeType2StateImpl(logic, state, iv);
}

u16 DecodeType2Word(const Type2Logic& logic, Type2State& state, u16 cipher_word, std::span<const u8> nonlinear_table)
{
  return DecodeType2WordImpl(logic, state, cipher_word, nonlinear_table);
}

