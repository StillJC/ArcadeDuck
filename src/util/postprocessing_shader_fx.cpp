static RenderAPI GetRenderAPI()
{
  return g_gpu_device ? g_gpu_device->GetRenderAPI() : RenderAPI::D3D11;
}

static bool PreprocessorFileExistsCallback(const std::string& path)
{
  // ReShadeFX constructs include candidates with std::filesystem, so use its
  // native filesystem path handling first for user/package shaders.
  if (reshadefx::preprocessor::stdfs_file_exists_callback(path))
    return true;

  // Bundled ArcadeDuck includes are resource-relative rather than disk files.
  return !Path::IsAbsolute(path) && Host::ResourceFileExists(path.c_str(), true);
}

static bool PreprocessorReadFileCallback(const std::string& path, std::string& data)
{
  // Match ReShadeFX's own default filesystem reader for paths generated by its
  // preprocessor. Fall back to ArcadeDuck resources only for relative paths.
  if (reshadefx::preprocessor::stdfs_read_file_callback(path, data))
    return true;

  if (Path::IsAbsolute(path))
    return false;

  std::optional<std::string> rdata = Host::ReadResourceFileToString(path.c_str(), true);
  if (!rdata.has_value())
    return false;

  data = std::move(rdata.value());
  return true;
}
static std::unique_ptr<reshadefx::codegen> CreateRFXCodegen()
{
  const bool debug_info = g_gpu_device ? g_gpu_device->IsDebugDevice() : false;
  const bool uniforms_to_spec_constants = false;
  const RenderAPI rapi = GetRenderAPI();

  switch (rapi)
  {
    case RenderAPI::None:
    case RenderAPI::D3D11:
    case RenderAPI::D3D12:
      return std::unique_ptr<reshadefx::codegen>(
        reshadefx::create_codegen_hlsl(50, debug_info, uniforms_to_spec_constants));

    case RenderAPI::Vulkan:
    case RenderAPI::Metal:
      return std::unique_ptr<reshadefx::codegen>(reshadefx::create_codegen_glsl(
        true, debug_info, uniforms_to_spec_constants, false, (rapi == RenderAPI::Vulkan)));

    case RenderAPI::OpenGL:
    case RenderAPI::OpenGLES:
    default:
      return std::unique_ptr<reshadefx::codegen>(
        reshadefx::create_codegen_glsl(false, debug_info, uniforms_to_spec_constants, false, true));
  }
}

