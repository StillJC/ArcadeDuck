bool PostProcessing::ReShadeFXShader::LoadFromFile(std::string name, std::string filename, bool only_config,
                                                   Error* error)
{
  std::optional<std::string> data = FileSystem::ReadFileToString(filename.c_str(), error);
  if (!data.has_value())
  {
    ERROR_LOG("Failed to read '{}'.", filename);
    return false;
  }

  return LoadFromString(std::move(name), std::move(filename), std::move(data.value()), only_config, error);
}

bool PostProcessing::ReShadeFXShader::LoadFromString(std::string name, std::string filename, std::string code,
                                                     bool only_config, Error* error)
{
  DebugAssert(only_config || g_gpu_device);

  m_name = std::move(name);
  m_filename = std::move(filename);

  // ReShade's preprocessor expects this.
  if (code.empty() || code.back() != '\n')
    code.push_back('\n');

  reshadefx::effect_module temp_module;
  if (!CreateModule(only_config ? DEFAULT_BUFFER_WIDTH : g_gpu_device->GetWindowWidth(),
                    only_config ? DEFAULT_BUFFER_HEIGHT : g_gpu_device->GetWindowHeight(), &temp_module, nullptr,
                    std::move(code), error))
  {
    return false;
  }

  if (!CreateOptions(temp_module, error))
    return false;

  bool has_passes = false;
  for (const reshadefx::technique& tech : temp_module.techniques)
  {
    for (const reshadefx::pass& pi : tech.passes)
    {
      has_passes = true;

      if (!pi.cs_entry_point.empty())
      {
        Error::SetString(error, fmt::format("Compute pass '{}' is not supported by ArcadeDuck post-processing.", pi.name));
        return false;
      }
      if (!pi.storage_bindings.empty())
      {
        Error::SetString(error,
                         fmt::format("Storage/UAV bindings in pass '{}' are not supported by ArcadeDuck post-processing.",
                                     pi.name));
        return false;
      }

      u32 num_render_targets = 0;
      for (const std::string& rtname : pi.render_target_names)
      {
        if (rtname.empty())
          break;
        num_render_targets++;
      }
      if (num_render_targets > GPUDevice::MAX_RENDER_TARGETS)
      {
        Error::SetString(error,
                         fmt::format("Too many render targets ({}) in pass '{}', only {} are supported.",
                                     num_render_targets, pi.name, GPUDevice::MAX_RENDER_TARGETS));
        return false;
      }

      for (const reshadefx::texture_binding& binding : pi.texture_bindings)
      {
        if (binding.entry_point_binding >= GPUDevice::MAX_TEXTURE_SAMPLERS)
        {
          Error::SetString(error,
                           fmt::format("Texture binding {} in pass '{}' exceeds ArcadeDuck's {} texture slots.",
                                       binding.entry_point_binding, pi.name, GPUDevice::MAX_TEXTURE_SAMPLERS));
          return false;
        }
      }
      for (const reshadefx::sampler_binding& binding : pi.sampler_bindings)
      {
        if (binding.entry_point_binding >= GPUDevice::MAX_TEXTURE_SAMPLERS)
        {
          Error::SetString(error,
                           fmt::format("Sampler binding {} in pass '{}' exceeds ArcadeDuck's {} sampler slots.",
                                       binding.entry_point_binding, pi.name, GPUDevice::MAX_TEXTURE_SAMPLERS));
          return false;
        }
      }
    }
  }

  if (!has_passes)
  {
    Error::SetString(error, "No passes defined in file.");
    return false;
  }

  // Might go invalid when creating pipelines.
  m_valid = true;
  return true;
}

