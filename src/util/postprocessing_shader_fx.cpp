static GPUSampler::Config MapSampler(const reshadefx::sampler& si)
{
  GPUSampler::Config config = GPUSampler::GetNearestConfig();

  switch (si.filter)
  {
    case reshadefx::filter_mode::min_mag_mip_point:
      config.min_filter = GPUSampler::Filter::Nearest;
      config.mag_filter = GPUSampler::Filter::Nearest;
      config.mip_filter = GPUSampler::Filter::Nearest;
      break;

    case reshadefx::filter_mode::min_mag_point_mip_linear:
      config.min_filter = GPUSampler::Filter::Nearest;
      config.mag_filter = GPUSampler::Filter::Nearest;
      config.mip_filter = GPUSampler::Filter::Linear;
      break;

    case reshadefx::filter_mode::min_point_mag_linear_mip_point:
      config.min_filter = GPUSampler::Filter::Linear;
      config.mag_filter = GPUSampler::Filter::Linear;
      config.mip_filter = GPUSampler::Filter::Nearest;
      break;

    case reshadefx::filter_mode::min_point_mag_mip_linear:
      config.min_filter = GPUSampler::Filter::Nearest;
      config.mag_filter = GPUSampler::Filter::Linear;
      config.mip_filter = GPUSampler::Filter::Linear;
      break;

    case reshadefx::filter_mode::min_linear_mag_mip_point:
      config.min_filter = GPUSampler::Filter::Linear;
      config.mag_filter = GPUSampler::Filter::Nearest;
      config.mip_filter = GPUSampler::Filter::Nearest;
      break;

    case reshadefx::filter_mode::min_linear_mag_point_mip_linear:
      config.min_filter = GPUSampler::Filter::Linear;
      config.mag_filter = GPUSampler::Filter::Nearest;
      config.mip_filter = GPUSampler::Filter::Linear;
      break;

    case reshadefx::filter_mode::min_mag_linear_mip_point:
      config.min_filter = GPUSampler::Filter::Linear;
      config.mag_filter = GPUSampler::Filter::Linear;
      config.mip_filter = GPUSampler::Filter::Nearest;
      break;

    case reshadefx::filter_mode::min_mag_mip_linear:
      config.min_filter = GPUSampler::Filter::Linear;
      config.mag_filter = GPUSampler::Filter::Linear;
      config.mip_filter = GPUSampler::Filter::Linear;
      break;

    default:
      break;
  }

  static constexpr auto map_address_mode = [](const reshadefx::texture_address_mode m) {
    switch (m)
    {
      case reshadefx::texture_address_mode::wrap:
        return GPUSampler::AddressMode::Repeat;
      case reshadefx::texture_address_mode::mirror:
        return GPUSampler::AddressMode::MirrorRepeat;
      case reshadefx::texture_address_mode::clamp:
        return GPUSampler::AddressMode::ClampToEdge;
      case reshadefx::texture_address_mode::border:
      default:
        return GPUSampler::AddressMode::ClampToBorder;
    }
  };

  config.address_u = map_address_mode(si.address_u);
  config.address_v = map_address_mode(si.address_v);
  config.address_w = map_address_mode(si.address_w);

  return config;
}

static GPUPipeline::BlendState MapBlendState(const reshadefx::pass& pass)
{
  // ReShadeFX enum values are stable wire-style values. Keep the translation
  // local and bounds-checked rather than mirroring the parser's switch layout.
  static constexpr std::array<GPUPipeline::BlendOp, 5> BLEND_OPERATIONS = {
    GPUPipeline::BlendOp::Add,
    GPUPipeline::BlendOp::Subtract,
    GPUPipeline::BlendOp::ReverseSubtract,
    GPUPipeline::BlendOp::Min,
    GPUPipeline::BlendOp::Max,
  };

  static constexpr std::array<GPUPipeline::BlendFunc, 10> BLEND_FACTORS = {
    GPUPipeline::BlendFunc::Zero,
    GPUPipeline::BlendFunc::One,
    GPUPipeline::BlendFunc::SrcColor,
    GPUPipeline::BlendFunc::InvSrcColor,
    GPUPipeline::BlendFunc::DstColor,
    GPUPipeline::BlendFunc::InvDstColor,
    GPUPipeline::BlendFunc::SrcAlpha,
    GPUPipeline::BlendFunc::InvSrcAlpha,
    GPUPipeline::BlendFunc::DstAlpha,
    GPUPipeline::BlendFunc::InvDstAlpha,
  };

  const auto decode_operation = [](reshadefx::blend_op value) {
    const u32 encoded = static_cast<u32>(value);
    return (encoded >= 1 && encoded <= BLEND_OPERATIONS.size()) ?
             BLEND_OPERATIONS[encoded - 1] :
             GPUPipeline::BlendOp::Max;
  };

  const auto decode_factor = [](reshadefx::blend_factor value) {
    const u32 encoded = static_cast<u32>(value);
    return (encoded < BLEND_FACTORS.size()) ? BLEND_FACTORS[encoded] : GPUPipeline::BlendFunc::InvDstAlpha;
  };

  constexpr size_t RT = 0;

  GPUPipeline::BlendState state = GPUPipeline::BlendState::GetNoBlendingState();
  state.enable = pass.blend_enable[RT];
  state.blend_op = decode_operation(pass.color_blend_op[RT]);
  state.src_blend = decode_factor(pass.source_color_blend_factor[RT]);
  state.dst_blend = decode_factor(pass.dest_color_blend_factor[RT]);
  state.alpha_blend_op = decode_operation(pass.alpha_blend_op[RT]);
  state.src_alpha_blend = decode_factor(pass.source_alpha_blend_factor[RT]);
  state.dst_alpha_blend = decode_factor(pass.dest_alpha_blend_factor[RT]);
  state.write_mask = pass.render_target_write_mask[RT];
  return state;
}

static GPUPipeline::Primitive MapPrimitive(reshadefx::primitive_topology topology)
{
  switch (topology)
  {
    case reshadefx::primitive_topology::point_list:
      return GPUPipeline::Primitive::Points;
    case reshadefx::primitive_topology::line_list:
      return GPUPipeline::Primitive::Lines;
    case reshadefx::primitive_topology::line_strip:
      Panic("Unhandled line strip");
    case reshadefx::primitive_topology::triangle_list:
      return GPUPipeline::Primitive::Triangles;
    case reshadefx::primitive_topology::triangle_strip:
    default:
      return GPUPipeline::Primitive::TriangleStrips;
  }
}

